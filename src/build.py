def page(slug):
    d = PAGES[slug]
    pre = "../"
    h1 = T(d["h1"])
    others = [(s, t) for s, t in MENU if s != slug][:8]
    rel = '<div class="related">' + "".join(f'<a href="{s}.html">{esc(t)}</a>' for s, t in others) + "</div>"
    body = "".join(render_blocks(d["blocks"], pre))
    inner = f'''<main class="wrap"><p class="crumbs"><a href="../index.html">Главная</a> / {esc(dict(MENU)[slug])}</p>
<h1>{esc(h1)}</h1>{brand_card()}<div style="margin-top:6px">{body}</div>
<h2>Читайте также</h2>{rel}</main><div class="wrap">{prov_strip(pre)}</div>'''
    return doc(f"{h1} | {BRAND}", T(d["desc"]), inner, pre, slug)


